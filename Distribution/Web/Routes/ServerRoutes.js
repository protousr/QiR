import { ServerController } from "../Controllers/ServerController.js";
import { RequireAuth } from "../Middleware/AuthMiddleware.js";
export async function ServerRoutes(fastify) {
    fastify.addHook("preHandler", RequireAuth);
    const controller = new ServerController();
    fastify.get("/servers", controller.GetAllServers);
    fastify.get("/servers/:Id", controller.GetServerById);
    fastify.post("/servers", controller.CreateServer);
    fastify.post("/servers/:Id/start", controller.StartServer);
    fastify.post("/servers/:Id/stop", controller.StopServer);
    fastify.post("/servers/:Id/kill", controller.KillServer);
    fastify.post("/servers/:Id/restart", controller.RestartServer);
    fastify.delete("/servers/:Id", controller.DeleteServer);
    fastify.get("/servers/:Id/inspect", controller.InspectServer);
    fastify.patch("/servers/:Id/config", controller.UpdateServerConfig);
    fastify.put("/servers/:Id/env", controller.UpdateEnvironmentVariables);
    fastify.put("/servers/:Id/restart-policy", controller.UpdateRestartPolicy);
    fastify.post("/servers/:Id/command", controller.SendCommand);
    fastify.get("/servers/:Id/logs", controller.GetLogs);
    fastify.get("/servers/:Id/files", controller.ListVolumeFiles);
    fastify.delete("/servers/:Id/files", controller.DeleteVolumeFile);
    fastify.get("/servers/:Id/files/content", controller.ReadVolumeFile);
    fastify.post("/servers/:Id/files/content", controller.WriteVolumeFile);
    fastify.get("/servers/:Id/files/download", controller.DownloadVolumeFile);
    fastify.post("/servers/:Id/files/upload", controller.UploadVolumeFile);
    fastify.post("/servers/:Id/files/mkdir", controller.CreateVolumeDirectory);
    fastify.post("/servers/:Id/files/rename", controller.RenameVolumeFile);
    fastify.post("/servers/:Id/files/extract", controller.ExtractVolumeArchive);
    fastify.post("/servers/:Id/files/compress", controller.CompressVolumeFiles);
    fastify.put("/servers/:Id/alert-webhook", controller.UpdateAlertWebhook);
    fastify.post("/servers/:Id/test-alert-webhook", controller.TestAlertWebhook);
    fastify.get("/servers/:Id/backups", controller.ListBackups);
    fastify.post("/servers/:Id/backups", controller.CreateBackup);
    fastify.post("/servers/:Id/backups/:FileName/restore", controller.RestoreBackup);
    fastify.delete("/servers/:Id/backups/:FileName", controller.DeleteBackup);
    fastify.get("/servers/:Id/backups/:FileName/download", controller.DownloadBackup);
    fastify.get("/servers/:Id/audit", controller.GetServerAuditLogs);
    fastify.post("/servers/bulk/start", controller.BulkStart);
    fastify.post("/servers/bulk/stop", controller.BulkStop);
    fastify.post("/servers/:Id/ports", controller.AddPort);
    fastify.delete("/servers/:Id/ports/:ContainerPort/:Protocol", controller.RemovePort);
    fastify.post("/servers/:Id/clone", controller.CloneServer);
    fastify.get("/servers/:Id/schedules", controller.GetSchedules);
    fastify.post("/servers/:Id/schedules", controller.CreateSchedule);
    fastify.delete("/servers/:Id/schedules/:ScheduleId", controller.DeleteSchedule);
    fastify.post("/servers/:Id/schedules/:ScheduleId/run", controller.RunSchedule);
    fastify.get("/servers/:Id/webhook", controller.GetWebhook);
    fastify.post("/servers/:Id/webhook/rotate", controller.RotateWebhook);
}
